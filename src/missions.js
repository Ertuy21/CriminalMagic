// ---------------------------------------------------------------------------
export class Missions {
  constructor(game) {
    this.game = game;
    this.current = null;
    this.task = null;
    this.mapMarkers = [];
    this.interaction = null;
    this.contracts = [];
    this.storyIndex = 0;
    this.active = false;
    this.running = false;
    this._stop = false;
    this._barrierP = 0;
    this.contractSeq = 0;
    this.missionAgents = [];
    this.barrier = null;
    this._genContracts(4);
  }

  // -----------------------------------------------------------------------
  // task helpers
  // -----------------------------------------------------------------------
  async chapter(num, title, sub) {
    const g = this.game;
    g.mode = 'cutscene';
    g.ui.setMission(null);
    await g.ui.showChapter(num, title, sub);
    g.mode = 'play';
  }

  begin(title, opts = {}) {
    const g = this.game;
    this.current = { ...(this.current || {}), title, ...opts };
    g.inMission = true;
    g.ui.setMission({ kicker: opts.kicker || 'ОПЕРАЦИЯ', title, obj: opts.objective || '', progress: 0 });
    g.audio?.play('ui');
  }

  objective(text, progress = 0) {
    if (this.game.ui) this.game.ui.setObjective(text, progress);
  }

  marker(x, z, label = 'ЦЕЛЬ') {
    this.mapMarkers = [{ type: 'mission', x, z, label }];
    this.game.setWaypoint(x, z, label);
  }

  clearMarker() {
    this.mapMarkers = [];
    this.game.clearWaypoint();
  }

  waitGoto(x, z, r, text, timeout = 0) {
    const g = this.game;
    g.ui.setMission({
      kicker: this.kicker(), title: this.current?.title || '', obj: text, progress: 0,
    });
    this.marker(x, z, text);
    return new Promise((resolve, reject) => {
      this.task = { type: 'goto', x, z, r, resolve, reject, text, timeout, t: 0 };
    });
  }

  waitUntil(fn, text, opts = {}) {
    this.objective(text, opts.progress || 0);
    if (opts.x !== undefined) this.marker(opts.x, opts.z, text);
    return new Promise((resolve, reject) => {
      this.task = { type: 'until', fn, text, resolve, reject, x: opts.x, z: opts.z, t: 0, timeout: opts.timeout || 0 };
    });
  }

  wait(seconds, text, sub = '') {
    this.objective(text + (sub ? ' · ' + sub : ''));
    return new Promise((resolve) => {
      this.task = { type: 'timer', t: 0, max: seconds, resolve, text };
    });
  }

  kill(agents, text) {
    this.objective(text, 0);
    return new Promise((resolve) => {
      this.task = { type: 'kill', agents, resolve, text };
    }).then(() => this.clearMarker());
  }

  kicker() {
    const i = this.current?.i ?? (this.game.state.storyDone || 0);
    const n = String(i + 1).padStart(2, '0');
    return `ОПЕРАЦИЯ ${n} / 45 · ГЛАВА ${chapterFor(i).num}`;
  }

  update(dt) {
    const g = this.game;
    if (!this.current && this.pendingStory && !this.running) {
      const p = g.player.pos;
      if (Math.hypot(p.x - this.pendingStory.x, p.z - this.pendingStory.z) < (this.pendingStory.r || 6.5)) {
        const st = this.pendingStory;
        this.pendingStory = null;
        this.runMission(st.index);
      }
    }
    if (!this.task) return;
    const t = this.task;
    t.t += dt;
    if (t.type === 'goto') {
      const p = g.player.pos;
      const d = Math.hypot(p.x - t.x, p.z - t.z);
      g.ui.setObjective(`${t.text} · ${Math.round(d)} М`, clamp(1 - d / 260, 0, 0.95));
      if (d < t.r) {
        this.task = null;
        t.resolve();
      } else if (t.timeout && t.t > t.timeout) {
        this.task = null;
        t.resolve('timeout');
      }
    } else if (t.type === 'until') {
      if (t.fn()) {
        this.task = null;
        t.resolve();
      } else if (t.timeout && t.t > t.timeout) {
        this.task = null;
        t.resolve('timeout');
      }
    } else if (t.type === 'timer') {
      g.ui.setObjective(`${t.text} · ${Math.ceil(t.max - t.t)} С`, t.t / t.max);
      if (t.t >= t.max) {
        this.task = null;
        t.resolve();
      }
    } else if (t.type === 'kill') {
      const alive = t.agents.filter(a => a.active && !a.down).length;
      const total = t.agents.length || 1;
      g.ui.setObjective(`${t.text} · ${total - alive} / ${total}`, 1 - alive / total);
      if (alive === 0) {
        this.task = null;
        t.resolve();
      }
    }
  }

  // -----------------------------------------------------------------------
  spawnThugs(n, x, z, radius = 10, hpBase = 60) {
    const g = this.game;
    const out = [];
    for (let i = 0; i < n; i++) {
      let a = g.crowd.agents.find(a => !a.active || a.down);
      if (!a) {
        if (g.crowd.agents.length >= g.crowd.max) break;
        a = { active: false, type: 'thug', x: 0, z: 0, yaw: 0, speed: 0, phase: rand(0, 6), state: 'walk', target: { x, z }, timer: 0, hp: 60, down: false, coat: 0, pants: 0, skin: 0, cap: false, color: 0 };
        g.crowd.agents.push(a);
      }
      g.crowd.spawnAgent(a, x, z, 'thug');
      a.x = x + Math.cos((i / n) * Math.PI * 2) * radius;
      a.z = z + Math.sin((i / n) * Math.PI * 2) * radius;
      a.hp = hpBase + i * 5;
      a.speed = 3.4;
      a.state = 'chase';
      a.mission = true;
      out.push(a);
    }
    this.missionAgents.push(...out);
    return out;
  }

  clearMissionAgents() {
    for (const a of this.missionAgents) { a.mission = false; a.active = false; }
    this.missionAgents = [];
  }

  // -----------------------------------------------------------------------
  // campaign flow
  // -----------------------------------------------------------------------
  async startCampaign() {
    if (this.active) return;
    this.active = true;
    const g = this.game;
    this.storyIndex = g.state.storyDone || 0;
    if (this.storyIndex >= STORY_TOTAL) return;
    if (this.storyIndex === 0) {
      await this.runMission(0);
    } else {
      g.mode = 'play';
      this.queueNext();
    }
  }

  queueNext() {
    const g = this.game;
    const i = g.state.storyDone || 0;
    if (i >= STORY_TOTAL) return;
    const m = MISSIONS[i];
    if (!m) return;
    // a start point must never sit inside geometry: nudge it out and widen the gate
    let sx = m.start[0], sz = m.start[1];
    const probe = { x: sx, z: sz };
    if (g.world.collideCircle(probe, 0.5)) {
      const dx = probe.x - sx, dz = probe.z - sz;
      sx = probe.x + Math.sign(dx || 1) * 1.5;
      sz = probe.z + Math.sign(dz || 1) * 1.5;
    }
    this.pendingStory = { index: i, x: sx, z: sz, r: 9 };
    this.mapMarkers = [{ type: 'mission', x: sx, z: sz, label: `ОПЕРАЦИЯ ${String(i + 1).padStart(2, '0')} · ${m.title}` }];
    g.setWaypoint(sx, sz, m.title);
    g.ui?.toast('ДОСТУПНА ОПЕРАЦИЯ: ' + m.title);
  }

  async runMission(i) {
    const g = this.game;
    if (this.running || this.current) return;
    if (i >= STORY_TOTAL) return;
    const m = MISSIONS[i];
    this.running = true;
    this._stop = false;
    this.storyIndex = i;
    g.state.storyDone = i;
    g.state.approach = null;
    const lockIds = m.beats.find(b => b && b.t === 'lock')?.ids || null;
    g.missionLock = lockIds;
    if (lockIds) g.ui?.setWheelLock?.(lockIds);
    if (lockIds && !lockIds.includes(g.player.id)) {
      const want = lockIds[0];
      if (g.heroes[want]) {
        g.heroes[want].pos.copy(g.player.pos);
        g.switchCharacter(want);
      }
    }
    this.current = { ...m, kicker: '' };
    this.clearMarker();
    this.begin(m.title, { kicker: `ОПЕРАЦИЯ ${String(i + 1).padStart(2, '0')} · ГЛАВА ${chapterFor(i).num}`, objective: 'ПОЛУЧИТЬ ЗАДАНИЕ' });
    g.save();
    try {
      for (const b of m.beats) {
        if (this._stop) break;
        await this.beat(b);
      }
    } catch (e) {
      console.warn('mission error', i, e);
    }
    this.running = false;
    this._stop = false;
    if (this.current && !this.current.done) {
      // soft recovery so the campaign never dead-ends
      this.finishMission({ reward: 800, bond: 0 });
    }
  }

  async beat(b) {
    const g = this.game;
    const ui = g.ui;
    if (!b || this._stop) return;
    switch (b.t) {
      case 'chapter': await this.chapter(b.c.num, b.c.title, b.c.sub); break;
      case 'say': await ui.say(b.lines); break;
      case 'ask': {
        const opts = b.opts.filter(o => !o.bondMin || g.state.bond >= o.bondMin);
        const labels = opts.map(o => ({ text: o.text, tag: o.tag }));
        const speaker = b.speaker === 'lucia' ? { name: 'ЛЮСИЯ', role: 'ВЗЛОМЩИЦА', accent: 'lucia' }
          : b.speaker === 'rey' ? { name: 'РЭЙ', role: 'ДИЛЕР', accent: 'narrator' }
          : undefined;
        const idx = await ui.ask(b.q, labels, speaker);
        const opt = opts[idx];
        if (opt) {
          if (opt.bond) g.addBond(opt.bond, opt.label);
          if (opt.flag) g.state.flags[opt.flag] = true;
          if (opt.cost && g.state.money >= opt.cost) { g.state.money -= opt.cost; g.ui.updateMoney(); }
          if (opt.say) await ui.say(opt.say);
        }
        break;
      }
      case 'goto': await this.waitGoto(b.x, b.z, b.r ?? 6, b.text, b.timeout || 0); break;
      case 'vehicle': {
        await this.objectiveStep('НАЙТИ ТРАНСПОРТ');
        if (b.x !== undefined) this.marker(b.x, b.z, b.text);
        await this.waitUntil(() => g.player.inVehicle, b.text, { x: b.x, z: b.z, timeout: 120 });
        break;
      }
      case 'drive': {
        if (b.x !== undefined) this.marker(b.x, b.z, b.text);
        await this.waitUntil(() => {
          const v = g.player.inVehicle;
          const d = Math.hypot(g.player.pos.x - b.x, g.player.pos.z - b.z);
          return v ? d < (b.r || 24) : d < (b.r || 24) * 0.55;
        }, b.text, { x: b.x, z: b.z, timeout: 180 });
        break;
      }
      case 'fight': {
        this.objective(b.text, 0);
        const mode = g.state.approach;
        let count = b.n;
        let hp = b.hp || 60;
        if (mode === 'stealth') { count = Math.max(1, b.n - 1); hp = Math.round(hp * 0.6); }
        if (mode === 'loud') count = b.n + 2;
        const agents = this.spawnThugs(count, b.x, b.z, b.radius || 10, hp);
        if (mode === 'stealth') {
          // nobody is alert yet: a quiet kill in the first seconds is free
          for (const a of agents) { a.state = 'idle'; a.speed = 0; a.unaware = 4.5; a.yaw = rand(0, TAU); }
          this.objective(b.text + ' · СКРЫТНО', 0);
        }
        await this.kill(agents, b.text);
        break;
      }
      case 'defend': {
        const start = g.elapsed;
        let next = 0;
        this.marker(b.x, b.z, b.text);
        await new Promise((resolve) => {
          this.task = {
            type: 'until', t: 0, text: b.text, resolve,
            fn: () => {
              const t = g.elapsed - start;
              this.objective(`${b.text} · ${Math.max(0, Math.ceil(b.sec - t))} С`, clamp(t / b.sec, 0, 1));
              if (t > next && t < b.sec - 2) {
                next = t + 6;
                this.spawnThugs(Math.min(3, b.n || 3), b.x + rand(-9, 9), b.z + rand(-9, 9), 8);
              }
              return t >= b.sec;
            },
          };
        });
        this.clearMarker();
        break;
      }
      case 'escape': await this.waitUntil(() => g.state.wanted === 0, b.text, { timeout: b.timeout || 90 }); break;
      case 'artifact': {
        await this.waitGoto(b.x, b.z, 5, b.text);
        await this.waitUntil(() => g.state.artifacts.includes(b.id), b.text, { x: b.x, z: b.z, timeout: 140 });
        if (!g.state.artifacts.includes(b.id)) {
          const a = g.world.artifacts.find(k => k.id === b.id);
          if (a) g.gameplay.collectArtifact(a);
        }
        break;
      }
      case 'barrier': await this.runBarrier(b.x, b.z, b.text); break;
      case 'enchant': await this.runEnchant(b.text); break;
      case 'approach': await this.runApproach(); break;
      case 'lock': g.missionLock = b.ids; g.ui?.setWheelLock?.(b.ids); break;
      case 'wait': await this.wait(b.sec, b.text); break;
      case 'bond': g.addBond(b.n, b.label); break;
      case 'flag': g.state.flags[b.k] = b.v; break;
      case 'weather': g.world.setWeather(b.w); g.ui.toast(b.w === 'storm' ? 'ШТОРМ НАД ЛЕОНИДОЙ' : b.w === 'rain' ? 'ДОЖДЬ' : 'ЯСНО'); break;
      case 'wanted': g.setWanted(b.n); break;
      case 'ending': await this.showFinale(); break;
      case 'complete': await this.finishMission(b); break;
    }
  }

  async objectiveStep(text) {
    this.objective(text, 0);
    await new Promise(r => setTimeout(r, 300));
  }

  // -----------------------------------------------------------------------
  // how a job gets done: quiet, loud or with magic. The world reacts.
  // -----------------------------------------------------------------------
  async runApproach() {
    const g = this.game;
    if (g.state.approach) return;
    const options = [
      { text: 'Тихо. Никто не должен услышать.', tag: 'СКРЫТНО' },
      { text: 'Громко. Пусть запомнят.', tag: 'СИЛА' },
      { text: 'Магией. Быстро и неестественно.', tag: 'МАГИЯ' },
    ];
    const idx = await g.ui.ask('Как войдём?', options, { name: 'ЛЮСИЯ', role: 'ВЗЛОМЩИЦА', accent: 'lucia' });
    const mode = idx === 1 ? 'loud' : idx === 2 ? 'magic' : 'stealth';
    g.state.approach = mode;
    const mage = g.player.id === 'mage';
    if (mode === 'stealth') {
      g.addBond(3, 'ТИХИЙ ПОДХОД');
      g.ui.toast('СКРЫТНОСТЬ · ВРАГИ НЕ ЖДУТ');
      await g.ui.say([
        { who: 'lucia', text: 'Тогда без геройства. Пригнись и не свети магией.' },
      ]);
    } else if (mode === 'loud') {
      g.addBond(1, 'ГРОМКИЙ ПОДХОД');
      g.state.bounty = (g.state.bounty || 0) + 400;
      g.setWanted(Math.min(3, (g.state.wanted || 0) + 1));
      g.ui.toast('ГРОМКО · РОЗЫСК ПОСЛЕ ОПЕРАЦИИ');
      await g.ui.say([
        { who: 'lucia', text: 'Громко так громко. Только потом не жалуйся на копов.' },
      ]);
    } else {
      g.player.mana = g.player.manaMax;
      g.addBond(2, 'МАГИЧЕСКИЙ ПОДХОД');
      g.ui.toast(mage ? 'МАГИЯ · МАНА ВОССТАНОВЛЕНА' : 'МАГИЯ · ЛЮСИЯ ПРИКРОЕТ');
      await g.ui.say([
        { who: mage ? 'lucia' : 'mage', text: mage ? 'Небо в Вайс-Сити сегодня будет странным.' : 'Только не спали город. Я ещё хочу здесь жить.' },
      ]);
    }
  }

  async finishMission(b) {
    const g = this.game;
    const i = this.storyIndex;
    const reward = b.reward || 1000;
    const bondGain = b.bond || 0;
    this.current && (this.current.done = true);
    g.state.storyDone = i + 1;
    g.state.opsDone = Math.min(45, i + 1);
    g.state.money += reward;
    if (bondGain) g.addBond(bondGain, 'СОВМЕСТНАЯ ОПЕРАЦИЯ');
    if (g.state.approach === 'stealth') {
      g.addBond(2, 'ЧИСТАЯ РАБОТА');
      g.ui.toast('ТИХО · +$' + Math.round(reward * 0.15) + ' ЗА ЧИСТОТУ');
      g.state.money += Math.round(reward * 0.15);
    } else if (g.state.approach === 'loud' && g.state.bounty) {
      g.state.money = Math.max(0, g.state.money - g.state.bounty);
      g.ui.toast('ШТРАФ ЗА ШУМ · -$' + g.state.bounty, 'bad');
      g.state.bounty = 0;
    }
    g.missionLock = null;
    g.ui?.setWheelLock?.(null);
    g.state.approach = null;
    g.ui.updateMoney();
    g.ui.updateArtifacts();
    g.ui.toast(`ОПЕРАЦИЯ ЗАВЕРШЕНА · +$${reward}`);
    g.ui.hideMission();
    this.clearMarker();
    this.clearMissionAgents();
    g.inMission = false;
    this.current = null;
    this.task = null;
    this._stop = true;
    g.save();
    if (i + 1 < STORY_TOTAL) {
      await new Promise(r => setTimeout(r, 1000));
      this.queueNext();
    }
  }

  async showFinale() {
    const g = this.game;
    const artifacts = g.state.artifacts.length;
    const bond = g.state.bond;
    const options = [
      { text: 'Вернуться в XIV век. Оставить всё.', tag: 'ВОЗВРАЩЕНИЕ' },
      { text: 'Остаться в 2026-м. Построить империю с Люсией.', tag: 'ОСТАТЬСЯ' },
      { text: 'Уничтожить разлом ценой себя.', tag: 'ЖЕРТВА' },
    ];
    if (bond >= 80 && artifacts >= 5) {
      options.push({ text: 'Открыть свой портал. Уйти вдвоём.', tag: 'СКРЫТО' });
    } else {
      g.ui.toast(`СКРЫТЫЙ ФИНАЛ: НУЖНЫ 5 ОСКОЛКОВ И СВЯЗЬ 80 · СВЯЗЬ ${Math.round(bond)} · ОСКОЛКИ ${artifacts}/5`, 'bad');
    }
    const choice = await g.ui.ask('Разлом ждёт. Что выберет Маг?', options, { name: 'МАГ', role: 'ОРДЕН ТЕНЕЙ' });
    let end = 'return';
    if (choice === 1) end = 'stay';
    if (choice === 2) end = 'sacrifice';
    if (choice === 3) end = 'hidden';
    g.state.ending = end;
    g.state.storyDone = STORY_TOTAL;
    g.state.opsDone = STORY_TOTAL;
    g.ui.hideMission();
    this.clearMarker();
    this.clearMissionAgents();
    g.inMission = false;
    this.current = null;
    this.task = null;
    this._stop = true;
    g.mode = 'ending';
    g.ui.showEnding(end);
    g.save();
  }

  // -----------------------------------------------------------------------
  runBarrier(x, z, text) {
    const g = this.game;
    this._spawnBarrier(x, z);
    this.marker(x, z, text);
    let p = 0;
    let last = g.elapsed;
    const started = g.elapsed;
    return new Promise((resolve) => {
      this.task = {
        type: 'until', t: 0, text, resolve,
        fn: () => {
          const d = Math.hypot(g.player.pos.x - x, g.player.pos.z - z);
          const now = g.elapsed;
          const dt = clamp(now - last, 0, 0.1);
          last = now;
          if (now - started > 120) { p = 1; return true; }
          if (d < 6 && g.mode === 'play') {
            p += dt * (g.player.id === 'lucia' ? 0.4 : 0.26);
            this.objective(text + (g.player.id === 'lucia' ? '' : ' · МАГИЯ МЕДЛЕННЕЕ'), clamp(p, 0, 1));
          } else if (d > 12) {
            p = Math.max(0, p - 0.002);
          }
          return p >= 1;
        },
      };
    }).then(() => {
      this._removeBarrier();
      this.clearMarker();
      g.ui.toast('БАРЬЕР СНЯТ');
      g.addBond(2, 'ТЕХНОЛОГИИ ПРОТИВ МАГИИ');
    });
  }

  _spawnBarrier(x, z) {
    const g = this.game;
    if (this.barrier) return;
    const grp = new THREE.Group();
    const mat = new THREE.MeshBasicMaterial({ color: 0x9d7bff, transparent: true, opacity: 0.32, side: THREE.DoubleSide, blending: THREE.AdditiveBlending, depthWrite: false, toneMapped: false });
    const wall = new THREE.Mesh(new THREE.PlaneGeometry(5, 4), mat);
    wall.position.y = 2;
    grp.add(wall);
    for (let i = 0; i < 3; i++) {
      const ring = new THREE.Mesh(new THREE.TorusGeometry(1.4 + i * 0.5, 0.03, 4, 24), new THREE.MeshBasicMaterial({ color: 0x4df3ff, transparent: true, opacity: 0.5, blending: THREE.AdditiveBlending, depthWrite: false, toneMapped: false }));
      ring.position.set(0, 2, 0);
      ring.rotation.y = Math.PI / 2;
      grp.add(ring);
    }
    grp.position.set(x, 0, z);
    g.scene.add(grp);
    const light = new THREE.PointLight(0x9d7bff, 18, 12, 2);
    light.position.set(x, 2.5, z);
    g.scene.add(light);
    this.barrier = { grp, light };
  }

  _removeBarrier() {
    if (!this.barrier) return;
    const g = this.game;
    g.scene.remove(this.barrier.grp);
    g.scene.remove(this.barrier.light);
    this.barrier = null;
    this._barrierP = 0;
  }

  runEnchant(text) {
    const g = this.game;
    const comp = g.companion;
    if (comp) this.marker(comp.pos.x, comp.pos.z, text);
    this.objective(text, 0);
    let t0 = g.elapsed;
    return new Promise((resolve) => {
      this.task = {
        type: 'until', t: 0, text, resolve,
        fn: () => {
          const d = comp ? Math.hypot(g.player.pos.x - comp.pos.x, g.player.pos.z - comp.pos.z) : 0;
          if (comp && comp.enchant > 0) return true;
          if (comp && d < 12 && g.elapsed - t0 > 2.2) {
            comp.enchant = 45;
            g.fx?.magic(comp.getMuzzleWorld(), 20, 0xff6fb5);
            g.ui.toast('ОРУЖИЕ ЛЮСИИ ЗАЧАРОВАНО');
            g.addBond(2, 'СОВМЕСТНАЯ МАГИЯ');
            return true;
          }
          return false;
        },
      };
    }).then(() => this.clearMarker());
  }

  // -----------------------------------------------------------------------
  // side contracts (free roam, 40 total)
  // -----------------------------------------------------------------------
  _roadPoint() {
    const p = this.game.world.randomStreetPoint();
    return this.game.world.roadPointNear(p.x, p.z, 500) || p;
  }

  _genContracts(n) {
    if (this.game.state.contractSeq === undefined) this.game.state.contractSeq = 0;
    while (this.contracts.length < n && (this.game.state.contractsDone + this.contracts.length) < CONTRACT_TOTAL) {
      const id = 'c' + (this.contractSeq++);
      const type = ['hit', 'delivery', 'race', 'heist'][this.contractSeq % 4];
      const p = this._roadPoint();
      const p2 = this._roadPoint();
      const reward = 350 + this.game.state.opsDone * 35 + Math.floor(rand(0, 250));
      this.contracts.push({
        id, type, reward,
        x: p.x, z: p.z, x2: p2.x, z2: p2.z,
        label: type === 'hit' ? 'ЗАЧИСТКА' : type === 'delivery' ? 'ДОСТАВКА' : type === 'race' ? 'ГОНКА' : 'ОГРАБЛЕНИЕ',
      });
      this.game.state.contractSeq = this.contractSeq;
    }
  }

  startContract(id) {
    if (this.current) { this.game.ui.toast('СНАЧАЛА ЗАВЕРШИ ТЕКУЩУЮ ОПЕРАЦИЮ', 'bad'); return; }
    const c = this.contracts.find(k => k.id === id);
    if (!c) return;
    this.contracts = this.contracts.filter(k => k.id !== id);
    this._genContracts(4);
    this.runContract(c);
  }

  async runContract(c) {
    const g = this.game;
    this.running = true;
    this._stop = false;
    this.current = { ...c, title: c.label };
    this.begin(c.label, { kicker: 'КОНТРАКТ', objective: 'ВЫПОЛНИТЬ ЗАКАЗ' });
    try {
      if (c.type === 'hit') {
        await this.waitGoto(c.x, c.z, 10, 'НАЙТИ ЦЕЛЬ');
        const enemies = this.spawnThugs(3, c.x, c.z, 8);
        await this.kill(enemies, 'УСТРАНИТЬ ЦЕЛЬ');
      } else if (c.type === 'delivery') {
        await this.waitGoto(c.x, c.z, 6, 'ЗАБРАТЬ ГРУЗ');
        await this.wait(2, 'ЗАГРУЗКА');
        await this.waitGoto(c.x2, c.z2, 6, 'ДОСТАВИТЬ ГРУЗ');
      } else if (c.type === 'race') {
        const pts = [c, { x: c.x2, z: c.z2 }, this._roadPoint(), this._roadPoint()];
        for (let i = 0; i < pts.length; i++) {
          await this.waitGoto(pts[i].x, pts[i].z, 10, `КОНТРОЛЬНАЯ ТОЧКА ${i + 1} / ${pts.length}`, 90);
        }
      } else {
        await this.waitGoto(c.x, c.z, 5, 'ПРОНИКНУТЬ В ЗДАНИЕ');
        await this.wait(5, 'ВСКРЫТЬ СЕЙФ');
        g.setWanted(2);
        await this.waitGoto(c.x2, c.z2, 8, 'УЙТИ ОТ ПОЛИЦИИ');
      }
      g.state.contractsDone = (g.state.contractsDone || 0) + 1;
      g.state.money += c.reward;
      g.ui.updateMoney();
      g.ui.toast(`КОНТРАКТ ВЫПОЛНЕН · +$${c.reward}`);
      g.ui.hideMission();
      this.clearMarker();
      this.clearMissionAgents();
      g.inMission = false;
      this.current = null;
      this.task = null;
      this._stop = true;
      g.addBond(2, 'СОВМЕСТНАЯ РАБОТА');
      g.save();
      this._genContracts(4);
    } catch (e) {
      console.warn(e);
      this.fail();
    }
    this.running = false;
    this._stop = false;
  }

  fail(text = 'ОПЕРАЦИЯ ПРОВАЛЕНА') {
    const g = this.game;
    g.ui.toast(text, 'bad');
    g.inMission = false;
    this.current = null;
    this.task = null;
    this._stop = true;
    this.clearMarker();
    this.clearMissionAgents();
    g.ui.hideMission();
    this.running = false;
    g.state.storyDone = this.storyIndex;
    g.save();
    this.queueNext();
  }

  getMapMarkers() {
    const out = [...this.mapMarkers];
    if (!this.current) {
      for (const c of this.contracts) {
        out.push({ type: 'contract', id: c.id, x: c.x, z: c.z, label: `${c.label} · $${c.reward}`, sub: 'КОНТРАКТ' });
      }
    }
    return out;
  }

  debugSkip() {
    if (this.task) {
      const t = this.task;
      this.task = null;
      t.resolve('skip');
    }
  }
}

function chapterFor(i) {
  if (i < 7) return CHAPTERS[0];
  if (i < 15) return CHAPTERS[1];
  if (i < 22) return CHAPTERS[2];
  if (i < 30) return CHAPTERS[3];
  if (i < 38) return CHAPTERS[4];
  return CHAPTERS[5];
}

